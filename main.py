if __name__ == "__main__":

    timer = PipelineTimer()

    timer.start_pipeline()

    try:

        print(
            "\n========================================"
        )

        print(
            "AI HTML/CSS VIDEO GENERATOR"
        )

        print(
            "========================================"
        )

        # ====================================================
        # TOPIC
        # ====================================================

        topic = input(
            "\nEnter video topic: "
        ).strip()

        if not topic:

            raise ValueError(
                "Topic cannot be empty."
            )

        # ====================================================
        # DURATION
        # ====================================================

        duration_input = input(
            "\nEnter video duration in seconds: "
        ).strip()

        try:

            duration = int(
                duration_input
            )

        except ValueError:

            raise ValueError(
                "Duration must be a whole "
                "number of seconds."
            )

        if duration <= 0:

            raise ValueError(
                "Duration must be greater than 0."
            )

        print(
            f"Requested duration: "
            f"{duration} seconds"
        )

        # ====================================================
        # TONE
        # ====================================================

        tone = input(
            "\nEnter video tone "
            "(default: educational): "
        ).strip() or "educational"

        # ====================================================
        # AUDIENCE
        # ====================================================

        audience = input(
            "Enter target audience "
            "(default: general audience): "
        ).strip() or "general audience"

        # ====================================================
        # LLM PROVIDER
        # ====================================================

        env_provider = os.getenv(
            "FRAMEFORGE_PROVIDER",
            "",
        ).strip().lower()

        if env_provider:

            provider = env_provider

            api_key = os.getenv(
                "FRAMEFORGE_API_KEY",
                "",
            ).strip()

            model = os.getenv(
                "FRAMEFORGE_MODEL",
                "",
            ).strip()

            base_url = os.getenv(
                "FRAMEFORGE_BASE_URL",
                "",
            ).strip()

            print(
                f"AI provider: {provider}"
            )

            if model:

                print(
                    f"Model: {model}"
                )

        else:

            provider = input(
                "\nAI provider "
                "[local/xai/openai/gemini/custom] "
                "(default: local): "
            ).strip().lower() or "local"

            api_key = ""

            model = ""

            base_url = ""

            if provider != "local":

                api_key = input(
                    "API key: "
                ).strip()

                model = input(
                    "Model (optional): "
                ).strip()

                if provider == "custom":

                    base_url = input(
                        "Custom OpenAI-compatible "
                        "base URL: "
                    ).strip()

        # ====================================================
        # PROVIDER VALIDATION
        # ====================================================

        supported_providers = {
            "local",
            "xai",
            "openai",
            "gemini",
            "custom",
        }

        if provider not in supported_providers:

            raise ValueError(
                f"Unsupported LLM provider: "
                f"{provider}. "
                f"Supported providers: "
                f"{sorted(supported_providers)}"
            )

        if (
            provider != "local"
            and not api_key
        ):

            raise ValueError(
                f"API key is required "
                f"for provider: {provider}"
            )

        if provider == "custom" and (
            not model
            or not base_url
        ):

            raise ValueError(
                "Custom provider requires "
                "both model and base_url."
            )

        # ====================================================
        # CLEAN VIDEO OUTPUTS
        # ====================================================

        clean_generated_outputs()

        # ====================================================
        # RUN LANGGRAPH
        # ====================================================

        timer.start_stage(
            "AI Agent Pipeline"
        )

        result = app.invoke(
            {
                "topic": topic,
                "duration": duration,
                "tone": tone,
                "audience": audience,

                "provider": provider,
                "api_key": api_key,
                "model": model,
                "base_url": base_url,

                "generate_video": False,
            }
        )

        timer.end_stage(
            "AI Agent Pipeline",
            True,
        )

        # ====================================================
        # SCRIPT NOT APPROVED
        # ====================================================

        if not result.get(
            "script_approved",
            False,
        ):

            print(
                "\nPipeline ended before "
                "video generation."
            )

            timer.end_pipeline(
                False
            )

            raise SystemExit(0)

        # ====================================================
        # SCRIPT-ONLY MODE
        #
        # IMPORTANT:
        #
        # script_only_end() already saved
        # the script.
        #
        # Do NOT run any video stage.
        # ====================================================

        if not result.get(
            "generate_video",
            False,
        ):

            print(
                "\n========================================"
            )

            print(
                "SCRIPT SAVED"
            )

            print(
                "========================================"
            )

            print(
                "\nThe pipeline stopped "
                "after script approval."
            )

            print(
                "No Scene Planner was executed "
                "after the script-only decision."
            )

            print(
                "\nFiles:"
            )

            print(
                "  output/scripts/approved_script.json"
            )

            print(
                "  output/scripts/approved_script.txt"
            )

            timer.end_pipeline(
                True
            )

            raise SystemExit(0)

        # ====================================================
        # VIDEO MODE
        #
        # Save approved script again here as a
        # safety/persistence point before video
        # generation.
        # ====================================================

        script = result[
            "script"
        ]

        save_video_script(
            script
        )

        # ====================================================
        # GET VIDEO STATE
        # ====================================================

        story = result[
            "story"
        ]

        video_plan = result[
            "video_plan"
        ]

        # ====================================================
        # VALIDATE STORY + PLAN
        # ====================================================

        validate_story_and_plan(
            story,
            video_plan,
            duration,
        )

        # ====================================================
        # ASSET VERIFICATION
        # ====================================================

        verification = result[
            "asset_verification"
        ]

        if not verification.get(
            "passed",
            False,
        ):

            print(
                "\n========================================"
            )

            print(
                "❌ REQUIRED IMAGES ARE MISSING"
            )

            print(
                "========================================"
            )

            for filename in verification.get(
                "missing_files",
                [],
            ):

                print(
                    f"❌ {filename}"
                )

            print(
                "\nGenerate the missing images "
                "and put them in "
                "assets/images/, "
                "then run the pipeline again."
            )

            timer.end_pipeline(
                False
            )

            raise SystemExit(1)

        # ====================================================
        # GENERATED HTML FILES
        # ====================================================

        generated_files = result[
            "generated_scene_files"
        ]

        print(
            "\n========================================"
        )

        print(
            "GENERATED SCENE FILES"
        )

        print(
            "========================================"
        )

        for file_path in generated_files:

            print(
                f"✅ {file_path}"
            )

        # ====================================================
        # BROWSER + FFMPEG
        # ====================================================

        final_video = (
            run_automated_render(
                video_plan,
                timer,
                result,
            )
        )

        # ====================================================
        # FINAL
        # ====================================================

        print(
            "\n========================================"
        )

        print(
            "🎉 FINAL VIDEO READY"
        )

        print(
            "========================================"
        )

        print(
            f"🎥 {final_video}"
        )

        timer.end_pipeline(
            True
        )

    # ========================================================
    # SYSTEM EXIT
    # ========================================================

    except SystemExit:

        raise

    # ========================================================
    # GENERAL ERROR
    # ========================================================

    except Exception as e:

        print(
            "\n========================================"
        )

        print(
            "❌ PIPELINE FAILED"
        )

        print(
            "========================================"
        )

        print(
            f"\nError: {e}"
        )

        timer.end_pipeline(
            False
        )

        raise
