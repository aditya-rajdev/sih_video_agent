# 12. SCRIPT APPROVAL GATE
# ============================================================

def script_preview_and_approval(
    state: VideoState
):
    """
    Script-first gate.

    Flow:

        Generate script
              ↓
        Show script
              ↓
        Edit / Regenerate
              ↓
        Approve
              ↓
        Ask video?
          /          \
        NO            YES
        ↓              ↓
     Save script    Video pipeline
     Stop
    """

    current_script = state["script"]

    # ========================================================
    # NON-INTERACTIVE / WEB MODE
    # ========================================================

    env_approval = os.getenv(
        "FRAMEFORGE_SCRIPT_APPROVED",
        "",
    ).strip().lower()

    env_generate_video = os.getenv(
        "FRAMEFORGE_GENERATE_VIDEO",
        "",
    ).strip().lower()

    if not sys.stdin.isatty():

        if env_approval not in {
            "1",
            "true",
            "yes",
            "y",
        }:
            raise RuntimeError(
                "SCRIPT_NOT_APPROVED: "
                "review the generated script first, "
                "then set "
                "FRAMEFORGE_SCRIPT_APPROVED=true."
            )

        validate_script(
            current_script,
            expected_duration=state["duration"],
        )

        print_script_preview(
            current_script
        )

        if env_generate_video not in {
            "1",
            "true",
            "yes",
            "y",
        }:

            print(
                "\nScript approved, but video "
                "generation was not requested."
            )

            return {
                "script": current_script,
                "script_approved": True,
                "generate_video": False,
                "script_status": "SCRIPT_ONLY",
            }

        print(
            "\nScript approved."
            "\nVideo generation requested."
            "\nProceeding to Scene Planner...\n"
        )

        return {
            "script": current_script,
            "script_approved": True,
            "generate_video": True,
            "script_status": "VIDEO_REQUESTED",
        }

    # ========================================================
    # INTERACTIVE CLI MODE
    # ========================================================

    while True:

        print_script_preview(
            current_script
        )

        print(
            "\nWhat would you like to do?"
            "\n[A] Approve script"
            "\n[E] Edit script"
            "\n[R] Regenerate script"
            "\n[Q] Quit"
        )

        choice = input(
            "\nChoose an action: "
        ).strip().lower()

        # ====================================================
        # APPROVE SCRIPT
        # ====================================================

        if choice in {
            "a",
            "approve",
            "yes",
            "y",
        }:

            validate_script(
                current_script,
                expected_duration=state["duration"],
            )

            state["script"] = current_script

            print(
                "\n========================================"
            )

            print(
                "SCRIPT APPROVED"
            )

            print(
                "========================================"
            )

            # IMPORTANT:
            #
            # Script approval and video generation
            # are TWO separate decisions.

            while True:

                video_choice = input(
                    "\nDo you want to generate a video "
                    "from this script? [Y]es / [N]o: "
                ).strip().lower()

                # ------------------------------------------------
                # YES -> VIDEO PIPELINE
                # ------------------------------------------------

                if video_choice in {
                    "y",
                    "yes",
                    "generate",
                    "video",
                }:

                    print(
                        "\nVideo generation requested."
                    )

                    print(
                        "Proceeding to Scene Planner...\n"
                    )

                    return {
                        "script": current_script,
                        "script_approved": True,
                        "generate_video": True,
                        "script_status": "VIDEO_REQUESTED",
                    }

                # ------------------------------------------------
                # NO -> SCRIPT ONLY
                # ------------------------------------------------

                if video_choice in {
                    "n",
                    "no",
                    "stop",
                    "quit",
                    "exit",
                }:

                    print(
                        "\n========================================"
                    )

                    print(
                        "SCRIPT MODE COMPLETE"
                    )

                    print(
                        "========================================"
                    )

                    print(
                        "\nApproved script will be saved."
                    )

                    print(
                        "Video generation was not started."
                    )

                    return {
                        "script": current_script,
                        "script_approved": True,
                        "generate_video": False,
                        "script_status": "SCRIPT_ONLY",
                    }

                print(
                    "Please enter Y or N."
                )

        # ====================================================
        # EDIT SCRIPT
        # ====================================================

        if choice in {
            "e",
            "edit",
            "edit script",
        }:

            instruction = input(
                "\nDescribe exactly what "
                "you want to change: "
            ).strip()

            if not instruction:

                print(
                    "Edit instruction cannot be empty."
                )

                continue

            print(
                "\nEditing script..."
            )

            llm = get_agent_llm(
                state
            )

            edited_script = edit_video_script(
                script=current_script,
                user_instruction=instruction,
                llm=llm,
            )

            validate_script(
                edited_script,
                expected_duration=state["duration"],
            )

            print(
                "\n========================================"
            )

            print(
                "SCRIPT UPDATED"
            )

            print(
                "========================================"
            )

            print(
                summarize_changes(
                    current_script,
                    edited_script,
                )
            )

            save_edited_script(
                edited_script
            )

            current_script = edited_script

            state["script"] = current_script

            state["script_status"] = (
                "SCRIPT_EDITED"
            )

            print(
                "\nUpdated script is ready "
                "for review."
            )

            continue

        # ====================================================
        # REGENERATE SCRIPT
        # ====================================================

        if choice in {
            "r",
            "regenerate",
        }:

            print(
                "\nRegenerating script..."
            )

            regenerated_script = (
                regenerate_script(
                    state
                )
            )

            validate_script(
                regenerated_script,
                expected_duration=state["duration"],
            )

            current_script = (
                regenerated_script
            )

            state["script"] = (
                current_script
            )

            state["script_status"] = (
                "SCRIPT_READY"
            )

            print(
                "\nNew script generated. "
                "Review it before approval."
            )

            continue

        # ====================================================
        # QUIT
        # ====================================================

        if choice in {
            "q",
            "quit",
            "exit",
        }:

            print(
                "\nScript generation "
                "stopped by user."
            )

            return {
                "script": current_script,
                "script_approved": False,
                "generate_video": False,
                "script_status": "CANCELLED",
            }

        print(
            "Invalid choice. "
            "Please select A, E, R, or Q."
        )


