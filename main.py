def save_video_script(
    script: VideoScript
):
    """
    Save approved standalone script
    as JSON and TXT.
    """

    output_dir = Path(
        "output/scripts"
    )

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    json_path = (
        output_dir
        / "approved_script.json"
    )

    txt_path = (
        output_dir
        / "approved_script.txt"
    )

    # ========================================================
    # JSON
    # ========================================================

    json_path.write_text(
        script.model_dump_json(
            indent=2
        ),
        encoding="utf-8",
    )

    # ========================================================
    # TXT
    # ========================================================

    lines = [
        f"TITLE: {script.title}",
        f"HOOK: {script.hook}",
        f"TONE: {script.tone}",
        f"AUDIENCE: {script.audience}",
        f"DURATION: {script.total_duration}s",
        "",
    ]

    for scene in script.scenes:

        lines.append(
            f"SCENE {scene.scene_id} "
            f"— {scene.duration}s"
        )

        lines.append(
            f"NARRATION: "
            f"{scene.narration}"
        )

        if scene.dialogues:

            lines.append(
                "DIALOGUE:"
            )

            for dialogue in scene.dialogues:

                lines.append(
                    f"{dialogue.character}: "
                    f"{dialogue.line}"
                )

        else:

            lines.append(
                "DIALOGUE: None"
            )

        lines.append(
            f"VISUAL DIRECTION: "
            f"{scene.visual_direction}"
        )

        lines.append(
            f"ON-SCREEN TEXT: "
            f"{scene.on_screen_text}"
        )

        lines.append("")

    lines.append(
        f"CTA: {script.cta}"
    )

    txt_path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )

    print(
        f"Approved script JSON: "
        f"{json_path}"
    )

    print(
        f"Approved script TXT:  "
        f"{txt_path}"
    )

    return (
        str(json_path),
        str(txt_path),
    )


